import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import mongoose from 'mongoose';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import api from './routes/api.js';
const app = express(); const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
app.use(cors()); app.use(express.json({ limit: '1mb' })); app.use('/api', api); app.use(express.static(path.join(root, 'client'))); app.get('/{*path}', (_req, res) => res.sendFile(path.join(root, 'client', 'index.html')));
if (process.env.MONGODB_URI) mongoose.connect(process.env.MONGODB_URI).then(() => console.log('MongoDB connected')).catch((error) => console.warn(`MongoDB unavailable: ${error.message}`));
app.listen(process.env.PORT || 3000, () => console.log(`MediNav running at http://localhost:${process.env.PORT || 3000}`));
